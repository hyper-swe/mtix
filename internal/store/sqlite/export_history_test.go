const historyGoldenPath = "testdata/export_history_off_golden.json"

// goldenStore returns a store holding exactly the board of the golden file,
// with the uids the golden file carries.
func goldenStore(t *testing.T) (*historyFixture, []byte) {
	t.Helper()
	raw, err := os.ReadFile(historyGoldenPath)
	require.NoError(t, err)
	var data sqlite.ExportData
	require.NoError(t, json.Unmarshal(raw, &data))
	f := newHistoryFixture(t)
	f.s.SetClock(func() time.Time { return time.Date(2026, 3, 14, 12, 0, 0, 0, time.UTC) })
	_, err = f.s.Import(context.Background(), &data, sqlite.ImportModeReplace, true)
	require.NoError(t, err)
	_, err = f.db.Exec("DELETE FROM task_history") // drop the import's own entries
	require.NoError(t, err)
	return f, raw
}

func marshalExport(t *testing.T, d *sqlite.ExportData) []byte {
	t.Helper()
	b, err := json.MarshalIndent(d, "", "  ")
	require.NoError(t, err)
	return b
}

// insertHistory writes one task_history row for uid.
func insertHistory(t *testing.T, db *sql.DB, id, uid, field string) {
	t.Helper()
	_, err := db.Exec(`INSERT INTO task_history (entry_id, task_uid, ts, actor, origin, kind, field, old_value, new_value, event_id)
		VALUES (?, ?, '2026-03-14T12:00:00.000000000Z', 'tester', 'local', 'change', ?, '"open"', '"done"', NULL)`, id, uid, field)
	require.NoError(t, err)
}

// goldenUIDs returns the uid of the golden root task.
func goldenRootUID(t *testing.T, raw []byte) string {
	t.Helper()
	var data sqlite.ExportData
	require.NoError(t, json.Unmarshal(raw, &data))
	require.NotEmpty(t, data.Nodes[0].UID)
	return data.Nodes[0].UID
}

// TestExport_HistorySwitchOff_ByteIdenticalToPreChangeExporter pins the bytes
// the exporter wrote before history export existed (file generated by the
// unchanged exporter): with the switch unset, off, or off after being on,
// history rows in the store change nothing.
func TestExport_HistorySwitchOff_ByteIdenticalToPreChangeExporter(t *testing.T) {
	f, raw := goldenStore(t)
	insertHistory(t, f.db, "01H0000000000000000000A001", goldenRootUID(t, raw), "status")
	insertHistory(t, f.db, "01H0000000000000000000A002", "ghost-uid", "status")
	ctx := context.Background()

	got, err := f.s.Export(ctx, "PROJ", "0.0.0-golden")
	require.NoError(t, err)
	require.Equal(t, string(raw), string(marshalExport(t, got)), "unset switch")

	f.s.SetHistoryExportSource(func() bool { return false })
	got, err = f.s.Export(ctx, "PROJ", "0.0.0-golden")
	require.NoError(t, err)
	require.Equal(t, string(raw), string(marshalExport(t, got)), "switch off")
}

// TestExport_HistorySwitchOn_WritesFormat210 covers the on path: version
// 2.1.0, per-node history, the last-writer version, and no placeholder task.
func TestExport_HistorySwitchOn_WritesFormat210(t *testing.T) {
	f, raw := goldenStore(t)
	uid := goldenRootUID(t, raw)
	insertHistory(t, f.db, "01H0000000000000000000A001", uid, "status")
	f.s.SetHistoryExportSource(func() bool { return true })
	f.s.SetWriterVersion("9.9.9-test")

	got, err := f.s.Export(context.Background(), "PROJ", "")
	require.NoError(t, err)
	require.Equal(t, "2.1.0", got.SchemaVersion)
	require.Equal(t, sqlite.SchemaVersionHistory, got.SchemaVersion)
	require.Equal(t, "9.9.9-test", got.MtixVersion, "the last writer's version is recorded")
	require.Len(t, got.Nodes, 2, "orphan history never becomes a task")
	require.Empty(t, got.History, "no orphans: the list is empty")

	out := string(marshalExport(t, got))
	require.Contains(t, out, "01H0000000000000000000A001")
	require.NotContains(t, out, "\n  \"history\"", "an empty top-level list is omitted")
	ok, err := sqlite.VerifyExportChecksum(got)
	require.NoError(t, err)
	require.True(t, ok)

	var back sqlite.ExportData
	require.NoError(t, json.Unmarshal([]byte(out), &back))
	nodeHist := 0
	for _, n := range back.Nodes {
		nodeHist += len(n.History)
	}
	require.Equal(t, 1, nodeHist)
}

// TestExport_HistorySwitchOn_OrphansInTopLevelListCoveredByChecksum: history
// of a task that no longer exists travels in the top-level list, and the
// checksum covers it.
func TestExport_HistorySwitchOn_OrphansInTopLevelListCoveredByChecksum(t *testing.T) {
	f, _ := goldenStore(t)
	insertHistory(t, f.db, "01H0000000000000000000B001", "ghost-uid", "status")
	f.s.SetHistoryExportSource(func() bool { return true })

	got, err := f.s.Export(context.Background(), "PROJ", "v")
	require.NoError(t, err)
	require.Len(t, got.History, 1)
	require.Equal(t, "ghost-uid", got.History[0].TaskUID)
	require.Contains(t, string(marshalExport(t, got)), "\n  \"history\": [")
	for _, n := range got.Nodes {
		require.Empty(t, n.History)
	}

	got.History[0].Actor = "tampered"
	ok, err := sqlite.VerifyExportChecksum(got)
	require.NoError(t, err)
	require.False(t, ok, "the checksum covers the top-level history list")
}

// TestImportReplace_HistoryRoundTrip_KeepsEveryEntryIncludingOrphans exports
// with the switch on, reads the file back and replace-imports it into a new
// store: every entry survives, orphans included.
func TestImportReplace_HistoryRoundTrip_KeepsEveryEntryIncludingOrphans(t *testing.T) {
	src, raw := goldenStore(t)
	uid := goldenRootUID(t, raw)
	insertHistory(t, src.db, "01H0000000000000000000C001", uid, "status")
	insertHistory(t, src.db, "01H0000000000000000000C002", "ghost-uid", "priority")
	src.s.SetHistoryExportSource(func() bool { return true })
	exp, err := src.s.Export(context.Background(), "PROJ", "v")
	require.NoError(t, err)
	var file sqlite.ExportData
	require.NoError(t, json.Unmarshal(marshalExport(t, exp), &file))

	dst := newHistoryFixture(t)
	_, err = dst.s.Import(context.Background(), &file, sqlite.ImportModeReplace, true)
	require.NoError(t, err)

	for _, id := range []string{"01H0000000000000000000C001", "01H0000000000000000000C002"} {
		var uidGot, field, oldV, newV, actor string
		require.NoError(t, dst.db.QueryRow(
			`SELECT task_uid, field, old_value, new_value, actor FROM task_history WHERE entry_id = ?`, id).
			Scan(&uidGot, &field, &oldV, &newV, &actor), id)
		require.Equal(t, `"open"`, oldV)
		require.Equal(t, `"done"`, newV)
		require.Equal(t, "tester", actor)
	}
	var ts string
	require.NoError(t, dst.db.QueryRow(`SELECT ts FROM task_history WHERE entry_id = ?`, "01H0000000000000000000C002").Scan(&ts))
	require.Equal(t, "2026-03-14T12:00:00.000000000Z", ts)

	// Importing the same file again adds nothing: entry ids are unique.
	var before, after int
	require.NoError(t, dst.db.QueryRow(`SELECT COUNT(*) FROM task_history WHERE entry_id LIKE '01H00000000000000000000C%' OR entry_id LIKE '01H0000000000000000000C%'`).Scan(&before))
	_, err = dst.s.Import(context.Background(), &file, sqlite.ImportModeReplace, true)
	require.NoError(t, err)
	require.NoError(t, dst.db.QueryRow(`SELECT COUNT(*) FROM task_history WHERE entry_id LIKE '01H00000000000000000000C%' OR entry_id LIKE '01H0000000000000000000C%'`).Scan(&after))
	require.Equal(t, before, after)
}

// TestImportReplace_HistoryEntryMissingFields_Rejected: an entry that cannot
// be stored is refused before anything is written.
func TestImportReplace_HistoryEntryMissingFields_Rejected(t *testing.T) {
	f, _ := goldenStore(t)
	f.s.SetHistoryExportSource(func() bool { return true })
	insertHistory(t, f.db, "01H0000000000000000000D001", "ghost-uid", "status")
	exp, err := f.s.Export(context.Background(), "PROJ", "v")
	require.NoError(t, err)
	exp.History[0].ID = ""
	require.NoError(t, sqlite.RecomputeExportChecksum(exp))
	_, err = f.s.Import(context.Background(), exp, sqlite.ImportModeReplace, true)
	require.Error(t, err)
	require.True(t, strings.Contains(err.Error(), "history"), err.Error())
}

// TestImport_IfStoreUnchanged_HoldsWithHistoryExportOn: the unchanged-store
// check hashes the store as Export does, history included, so an import
// guarded by an export's own checksum is not refused when history.export is on.
func TestImport_IfStoreUnchanged_HoldsWithHistoryExportOn(t *testing.T) {
	f, raw := goldenStore(t)
	insertHistory(t, f.db, "01H0000000000000000000E001", goldenRootUID(t, raw), "status")
	insertHistory(t, f.db, "01H0000000000000000000E002", "ghost-uid", "status")
	f.s.SetHistoryExportSource(func() bool { return true })
	ctx := context.Background()
	exp, err := f.s.Export(ctx, "PROJ", "v")
	require.NoError(t, err)
	_, err = f.s.Import(ctx, exp, sqlite.ImportModeReplace, true, sqlite.IfStoreUnchanged(exp.Checksum))
	require.NoError(t, err)
}
