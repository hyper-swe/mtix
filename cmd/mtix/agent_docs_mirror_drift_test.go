// MTIX-256: Commandment 15 needs every shipped agent document to equal the
// generated set. These guards render the documents with the production
// template data and compare whole files, not only managed sections.

const regenerateHint = "regenerate: run mtix docs generate / mtix plugin install in a scratch project and copy the file; a deliberate fix belongs in the template"

// renderedDocs renders every generated page into a map keyed by file name.
// The BYO Postgres workflow pages are not tracked under docs/ (they are
// guarded through their templates), so they are not rendered here.
func renderedDocs(t *testing.T) map[string]string {
	t.Helper()
	data := docs.BuildTemplateData(newRootCmd(), mcp.NewToolRegistry(), "PROJ", "dev")
	out := t.TempDir()
	gen, err := docs.NewEmbeddedGenerator(out, data, nil)
	require.NoError(t, err)
	_, err = gen.Generate(true)
	require.NoError(t, err)
	files := map[string]string{}
	for _, doc := range docs.AllDocFiles() {
		files[doc.Name] = readText(t, filepath.Join(out, doc.Name))
	}
	return files
}

// renderedClaudePlugin installs the claude-code skills for the repository's
// own prefix and returns them keyed by path relative to the skills directory.
func renderedClaudePlugin(t *testing.T) map[string]string {
	t.Helper()
	data := docs.BuildTemplateData(newRootCmd(), mcp.NewToolRegistry(), "MTIX", "dev")
	dir := t.TempDir()
	_, err := docs.NewPluginInstaller(dir, data, nil).Install("claude-code", false)
	require.NoError(t, err)
	files := map[string]string{}
	for _, doc := range docs.SkillDocFiles() {
		files[doc.Name] = readText(t, filepath.Join(dir, ".claude", "skills", doc.Name))
	}
	for _, doc := range docs.ReferenceDocFiles() {
		rel := filepath.Join("references", doc.Name)
		files[rel] = readText(t, filepath.Join(dir, ".claude", "skills", rel))
	}
	return files
}

// versionLineRE matches the generated header lines that name the mtix build,
// which differs by who ran the generator and is not document content.
var versionLineRE = regexp.MustCompile(`(?m)^(> (?:Auto-generated by|\*\*Generated by:\*\*) mtix )[^ \n]+`)

// markerRE matches the managed-section markers, which are not content.
var markerRE = regexp.MustCompile(`<!-- (?:END )?AUTO-GENERATED[^>]*-->`)

func normalizeVersion(text string) string { return versionLineRE.ReplaceAllString(text, "${1}VERSION") }

func readText(t *testing.T, path string) string {
	t.Helper()
	b, err := os.ReadFile(path) //nolint:gosec // repository and t.TempDir() paths
	require.NoError(t, err)
	return string(b)
}

func repoText(t *testing.T, rel string) string {
	t.Helper()
	return readText(t, filepath.Join("..", "..", filepath.FromSlash(rel)))
}

// TestAgentDocMirrors_DocsPagesEqualGeneratorOutput: each tracked docs page
// equals the generator output byte for byte.
func TestAgentDocMirrors_DocsPagesEqualGeneratorOutput(t *testing.T) {
	for rel, want := range renderedDocs(t) {
		if rel == "CLAUDE.md" {
			continue // rendered per project, not tracked (see internal/docs untrackedGeneratedDocs)
		}
		t.Run(rel, func(t *testing.T) {
			require.Equal(t, normalizeVersion(want), normalizeVersion(repoText(t, "docs/"+rel)), "docs/%s drifted from generator output; %s", rel, regenerateHint)
		})
	}
}

// TestAgentDocMirrors_ClaudePluginEqualsInstallOutput: each committed
// .claude-plugin skill and reference equals the installer output.
func TestAgentDocMirrors_ClaudePluginEqualsInstallOutput(t *testing.T) {
	for rel, want := range renderedClaudePlugin(t) {
		t.Run(rel, func(t *testing.T) {
			require.Equal(t, want, repoText(t, ".claude-plugin/skills/"+filepath.ToSlash(rel)), ".claude-plugin/skills/%s drifted from installer output; %s", rel, regenerateHint)
		})
	}
}

// skillBody drops a document's front matter and its first heading line.
func skillBody(text string) string {
	parts := strings.SplitN(text, "\n---\n", 2)
	body := parts[len(parts)-1]
	if i := strings.Index(body, "\n# "); i >= 0 {
		if j := strings.Index(body[i+1:], "\n"); j >= 0 {
			return body[i+1+j:]
		}
	}
	return body
}

// TestAgentDocMirrors_CodexSkillsFollowGenerator: the codex admin and sync
// skills carry the generated body; the condensed codex planning, review,
// task-execution and multi-agent skills and docs/codex/AGENTS.md hold no
// paragraph that is a stale copy of a generated one.
func TestAgentDocMirrors_CodexSkillsFollowGenerator(t *testing.T) {
	plugin := renderedClaudePlugin(t)
	for _, name := range []string{"admin", "sync"} {
		require.Equal(t, skillBody(plugin["mtix-"+name+".md"]), skillBody(repoText(t, ".codex-plugin/skills/"+name+"/SKILL.md")),
			".codex-plugin/skills/%s/SKILL.md body drifted from the generated skill; %s", name, regenerateHint)
	}
	pool := generatedPool(t)
	for _, name := range []string{"planning", "review", "task-execution", "multi-agent"} {
		rel := ".codex-plugin/skills/" + name + "/SKILL.md"
		require.Empty(t, staleParagraphs(repoText(t, rel), pool), "%s holds stale copies of generated paragraphs; %s", rel, regenerateHint)
	}
	require.Empty(t, staleParagraphs(repoText(t, "docs/codex/AGENTS.md"), pool),
		"docs/codex/AGENTS.md holds stale copies of generated paragraphs; %s", regenerateHint)
}

const staleKeyLen = 60

// generatedSkills returns the paragraphs of every generated plugin skill,
// keyed by their first staleKeyLen bytes.
func generatedSkills(t *testing.T) map[string][]string {
	t.Helper()
	pool := map[string][]string{}
	for _, text := range renderedClaudePlugin(t) {
		addParagraphs(pool, text)
	}
	return pool
}

// generatedPool adds the generated docs pages to the generated skills.
func generatedPool(t *testing.T) map[string][]string {
	t.Helper()
	pool := generatedSkills(t)
	for _, text := range renderedDocs(t) {
		addParagraphs(pool, text)
	}
	return pool
}

func addParagraphs(pool map[string][]string, text string) {
	for _, para := range paragraphs(text) {
		pool[para[:staleKeyLen]] = append(pool[para[:staleKeyLen]], para)
	}
}

// staleParagraphs lists the paragraphs of text that share their first
// staleKeyLen bytes with a pooled generated paragraph but equal none of them.
func staleParagraphs(text string, pool map[string][]string) []string {
	var stale []string
	for _, para := range paragraphs(text) {
		want, ok := pool[para[:staleKeyLen]]
		if ok && !slices.Contains(want, para) {
			stale = append(stale, para[:min(len(para), staleKeyLen+20)])
		}
	}
	return stale
}

// paragraphs splits text into blank-line separated paragraphs of at least
// staleKeyLen bytes, with code fences and headings left out.
func paragraphs(text string) []string {
	var out []string
	for _, para := range strings.Split(markerRE.ReplaceAllString(text, ""), "\n\n") {
		para = strings.Join(strings.Fields(para), " ")
		if len(para) >= staleKeyLen && !strings.HasPrefix(para, "#") && !strings.HasPrefix(para, "```") {
			out = append(out, para)
		}
	}
	return out
}

// TestStaleParagraphs_ShortOrLongParagraph_ReportsExcerptWithoutPanic checks
// that a stale paragraph shorter than the excerpt length (60 to 79 bytes) is
// reported whole rather than slicing past its end.
func TestStaleParagraphs_ShortOrLongParagraph_ReportsExcerptWithoutPanic(t *testing.T) {
	key := strings.Repeat("a", staleKeyLen)
	generated := key + strings.Repeat("b", 40)
	pool := map[string][]string{key: {generated}}

	tests := []struct {
		name string
		text string
		want []string
	}{
		{"short stale paragraph reported whole", key + "xyz", []string{key + "xyz"}},
		{"paragraph of exactly key length", key, []string{key}},
		{"long stale paragraph cut to excerpt", key + strings.Repeat("c", 40), []string{key + strings.Repeat("c", 20)}},
		{"paragraph equal to generated is not stale", generated, nil},
		{"paragraph with unknown key is not stale", strings.Repeat("z", 70), nil},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			require.NotPanics(t, func() {
				require.Equal(t, tt.want, staleParagraphs(tt.text, pool))
			})
		})
	}
}
