const agentsPointer = "Read [MTIX.md](MTIX.md) for mtix instructions."

// projectDoc records a planned write, after every user-owned input is validated.
type projectDoc struct {
	name          string
	before, after []byte
	exists        bool
}

// generateProjectBriefing implements FR-13.1 with one owned root document.
func generateProjectBriefing(root string, tmpl *template.Template, data *TemplateData) ([]GenerateResult, error) {
	content, err := renderProjectBriefing(tmpl, data)
	if err != nil {
		return nil, fmt.Errorf("prepare project briefing: %w", err)
	}
	owned := extractSections(string(content))
	// FR-13.3a documented STATUS_MACHINE as a legacy managed-section name.
	owned["STATUS_MACHINE"] = ""
	plans, err := planProjectDocs(root, owned)
	if err != nil {
		return nil, fmt.Errorf("prepare project briefing: %w", err)
	}
	plans[0].after = content
	var results []GenerateResult
	var pointers []string
	for _, plan := range plans {
		action := "skipped"
		if plan.after != nil && (!plan.exists || !bytes.Equal(plan.before, plan.after)) {
			if writeErr := writeRegularDoc(filepath.Join(root, plan.name), plan.after); writeErr != nil {
				return results, fmt.Errorf("write project briefing: %w", writeErr)
			}
			action = "generated"
			if plan.exists {
				action = "updated"
			}
		}
		if plan.name != "MTIX.md" && (plan.exists || plan.after != nil) {
			pointers = append(pointers, plan.name)
		}
		results = append(results, GenerateResult{File: plan.name, Action: action})
	}
	notice, excludeErr := excludeLocalBriefing(root, pointers)
	if excludeErr != nil {
		return results, fmt.Errorf("write project briefing: %w", excludeErr)
	}
	if notice != "" {
		results[0].Message = notice
	}
	return results, nil
}

func renderProjectBriefing(tmpl *template.Template, data *TemplateData) ([]byte, error) {
	if tmpl == nil || data == nil {
		return nil, fmt.Errorf("briefing templates and data are required")
	}
	rootData := *data
	rootData.DocsPath = ".mtix/docs/"
	var out bytes.Buffer
	out.WriteString("# MTIX.md — mtix project instructions\n\nThis file is owned by mtix and fully regenerated by `mtix docs generate`.\n\n")
	for _, name := range []string{"agents.md.tmpl", "claude.md.tmpl"} {
		if err := tmpl.ExecuteTemplate(&out, name, &rootData); err != nil {
			return nil, fmt.Errorf("render briefing %s: %w", name, err)
		}
		out.WriteString("\n")
	}
	return out.Bytes(), nil
}

func planProjectDocs(root string, owned map[string]string) ([]projectDoc, error) {
	var plans []projectDoc
	for _, name := range []string{"MTIX.md", "CLAUDE.md", "AGENTS.md"} {
		content, exists, err := readRegularDoc(filepath.Join(root, name))
		if err != nil {
			return nil, fmt.Errorf("prepare project briefing: %w", err)
		}
		plans = append(plans, projectDoc{name: name, before: content, exists: exists})
	}
	_, hsErr := os.Lstat(filepath.Join(root, "HYPERSWE.md"))
	if hsErr != nil && !os.IsNotExist(hsErr) {
		return nil, fmt.Errorf("inspect HYPERSWE.md: %w", hsErr)
	}
	for i := 1; i < len(plans); i++ {
		clean, err := stripProjectMarkers(plans[i].before, owned)
		if err != nil {
			return nil, fmt.Errorf("migrate %s: %w", plans[i].name, err)
		}
		pointer := "@MTIX.md"
		if plans[i].name == "AGENTS.md" {
			pointer = agentsPointer
		}
		if hsErr != nil {
			clean = appendProjectPointer(clean, pointer, plans[i].name)
		}
		if plans[i].exists || hsErr != nil {
			plans[i].after = clean
		}
	}
	return plans, nil
}

func appendProjectPointer(content []byte, pointer, name string) []byte {
	fenced := false
	for _, line := range strings.Split(string(content), "\n") {
		line = strings.TrimSpace(line)
		if strings.HasPrefix(line, "```") || strings.HasPrefix(line, "~~~") {
			fenced = !fenced
			continue
		}
		if !fenced && (line == pointer || (name == "AGENTS.md" && isAgentsPointer(line))) {
			return content
		}
	}
	out := append([]byte(nil), content...)
	if len(out) > 0 && out[len(out)-1] != '\n' {
		out = append(out, '\n')
	}
	return append(out, []byte(pointer+"\n")...)
}

func isAgentsPointer(line string) bool {
	for _, target := range []string{"MTIX.md", "`MTIX.md`", "[MTIX.md](MTIX.md)"} {
		for _, verb := range []string{"Read", "See"} {
			if line == verb+" "+target+" for mtix instructions." {
				return true
			}
		}
	}
	return false
}

// stripProjectMarkers removes only paired mtix marker bytes; all other bytes survive.
func stripProjectMarkers(content []byte, owned map[string]string) ([]byte, error) {
	text := string(content)
	blocks, err := projectMarkerBlocks(text)
	if err != nil {
		return nil, fmt.Errorf("prepare project briefing: %w", err)
	}
	var out strings.Builder
	offset := 0
	for _, block := range blocks {
		if _, remove := owned[block.name]; !remove {
			continue
		}
		out.WriteString(text[offset:block.start])
		offset = block.end
	}
	out.WriteString(text[offset:])
	return []byte(out.String()), nil
}

type projectMarkerBlock struct {
	name       string
	start, end int
}

func projectMarkerBlocks(text string) ([]projectMarkerBlock, error) {
	var blocks []projectMarkerBlock
	block := projectMarkerBlock{start: -1}
	offset := 0
	for offset < len(text) {
		at, opening, err := nextProjectMarker(text, offset)
		if err != nil {
			return nil, fmt.Errorf("prepare project briefing: %w", err)
		}
		if at < 0 {
			break
		}
		if opening {
			if block.start >= 0 {
				return nil, fmt.Errorf("nested auto-generated marker; repair marker pairs")
			}
			name, next, markerErr := projectMarkerName(text, at)
			if markerErr != nil {
				return nil, fmt.Errorf("prepare project briefing: %w", markerErr)
			}
			block = projectMarkerBlock{name: name, start: at}
			offset = next
		} else {
			if block.start < 0 {
				return nil, fmt.Errorf("orphan end marker; repair marker pairs")
			}
			offset = at + len(endMarker)
			block.end = offset
			blocks = append(blocks, block)
			block.start = -1
		}
	}
	if block.start >= 0 {
		return nil, fmt.Errorf("unclosed auto-generated marker; repair marker pairs")
	}
	return blocks, nil
}

func nextProjectMarker(text string, offset int) (int, bool, error) {
	open := strings.Index(text[offset:], "<!-- AUTO-GENERATED:")
	end := strings.Index(text[offset:], "<!-- END AUTO-GENERATED")
	if end >= 0 && !strings.HasPrefix(text[offset+end:], endMarker) {
		return 0, false, fmt.Errorf("malformed end marker")
	}
	if open < 0 && end < 0 {
		return -1, false, nil
	}
	if open >= 0 && (end < 0 || open < end) {
		return offset + open, true, nil
	}
	return offset + end, false, nil
}

func projectMarkerName(text string, start int) (string, int, error) {
	closeAt := strings.Index(text[start:], "-->")
	if closeAt < 0 {
		return "", 0, fmt.Errorf("unterminated auto-generated marker")
	}
	next := start + closeAt + 3
	tag := text[start:next]
	match := openMarkerRE.FindStringSubmatch(tag)
	if len(match) != 2 || match[0] != tag {
		return "", 0, fmt.Errorf("malformed auto-generated marker")
	}
	return match[1], next, nil
}
